"""由本次结果生成有数字支撑的背景解释、建议和运行报告。"""
import pandas as pd


def recommendations(tables):
    regions = tables['地区年度统计'].groupby('地区')['事件数'].sum().sort_values(ascending=False)
    top3 = regions.head(3)
    factors = tables['事件特征统计']
    attacks = factors[factors['维度'].eq('袭击类型')].groupby('类别')['事件数'].sum().sort_values(ascending=False)
    targets = factors[factors['维度'].eq('目标类型')].groupby('类别')['事件数'].sum().sort_values(ascending=False)
    country = tables['国家年度统计'].pivot(index='国家', columns='年份', values='事件数').fillna(0)
    growth = (country[2017] - country[2015]).sort_values(ascending=False).head(3)
    mena = tables['2017回测指标']
    mena = mena[(mena['地区'] == '中东与北非') & (mena['方案'] == '冻结方案')].iloc[0]
    return pd.DataFrame([
        {'维度': '冲突与治理背景',
         '数据证据': f'近三年前三地区为{"、".join(top3.index)}，占事件数{top3.sum()/39452:.1%}。',
         '背景解释': 'IEP报告将冲突、政治排斥和群体不满列为相关背景。事件表没有未发生事件的对照样本，不能估计它们的因果效应。',
         '建议': '重点地区优先配置民用设施保护、急救和事件核实资源，同时结合当地冲突与治理资料评估。', '证据来源': '附件1；S1'},
        {'维度': '袭击方式和目标',
         '数据证据': f'最多袭击类型为{attacks.index[0]}（{attacks.iloc[0]/39452:.1%}）；最多目标类型为{targets.index[0]}（{targets.iloc[0]/39452:.1%}）。',
         '背景解释': '方式、目标、归属记录是事件特征，不是已识别的发生原因。危害分数含情境编码，不能反向证明该特征致害。',
         '建议': '按实际方式和目标构成安排人员培训、公共场所应急预案与伤员救治能力。', '证据来源': '附件1；第一问评分'},
        {'维度': '地区扩张与收缩并存',
         '数据证据': '2017较2015增量靠前国家：' + '、'.join(f'{k}（+{v:.0f}起）' for k, v in growth.items()),
         '背景解释': '热点增减和新增活跃格仅表示空间重分布，不能识别组织传播、人员移动或真实传播链。',
         '建议': '总量下降时继续监测局部增长，跨地区信息共享以可核实线索为依据。', '证据来源': '附件1；S3'},
        {'维度': '招募与社会排斥', '数据证据': '附件缺少个体招募过程、人口暴露和反事实对照数据。',
         '背景解释': 'UNDP非洲访谈指出治理不满及具体国家行为可能成为招募触发背景，样本并非全球代表性样本。',
         '建议': '依法执法，同时开展社区预防、申诉沟通和重返社会支持，另行评估项目效果。', '证据来源': 'S2'},
        {'维度': '2018不确定性',
         '数据证据': f'独立回测只有2017一年；中东与北非名义95%月区间覆盖率为{mena["覆盖率95"]:.1%}。',
         '背景解释': '计数模型不含未来冲突、政策和组织迁移冲击；区间采用历史RMS正态近似。',
         '建议': '以区间做资源情景分析并保留应急容量，实际应用需新增观测后更新，不能据点预测直接撤减能力。', '证据来源': '2017独立回测；S1；S3'},
    ])


def write_analysis(tables, output):
    """运行报告随结果更新，README保留本次正式运行的摘要。"""
    annual = tables['年度概况']
    forecast = tables['2018年度预测'].set_index('地区').loc['全球']
    test = tables['2017回测指标']
    g = test[(test['地区'] == '全球') & (test['方案'] == '冻结方案')].iloc[0]
    b = test[(test['地区'] == '全球') & (test['方案'] == '季节朴素基线')].iloc[0]
    regions = tables['地区年度统计'].groupby('地区')['事件数'].sum().sort_values(ascending=False)
    lines = ['# 第三问运行分析报告', '',
             '描述2015—2017，预测截点为2017年末。本报告由同次运行的结果表生成。', '',
             '## 数据与近三年变化', '',
             '| 年份 | 事件数 | 平均危害 | 一级占比 | 有事件国家数 | 坐标覆盖率 |',
             '| --- | ---: | ---: | ---: | ---: | ---: |']
    for _, r in annual.iterrows():
        lines.append(f'| {int(r["年份"])} | {r["事件数"]:,.0f} | {r["平均危害"]:.4f} | {r["一级占比"]:.1%} | {r["有事件国家数"]:.0f} | {r["坐标覆盖率"]:.2%} |')
    lines += ['', f'前三地区为{"、".join(regions.head(3).index)}，合计占近三年事件数的{regions.head(3).sum()/39452:.1%}。',
              '危害得分为第一问全样本回顾性标尺，仅用于描述。一级最严重，五级最轻。累计危害对连续得分求和，不对等级编号求和。',
              '伤亡缺失不填零。已记录死亡人数含数据库记录的袭击者死亡，是已知值之和，不等于完整的受害者死亡人数。', '',
              '## 2018预测与历史验证', '',
              f'全球全年点预测 **{forecast["预测事件数"]:,.1f} 起**，相对2017年变化 **{forecast["相对2017变化率"]:.1%}**。',
              f'名义80%年度区间 **[{forecast["下限80"]:,.1f}, {forecast["上限80"]:,.1f}]**，名义95%年度区间 **[{forecast["下限95"]:,.1f}, {forecast["上限95"]:,.1f}]**。',
              f'2017全球月度MAE {g["MAE"]:.2f}、RMSE {g["RMSE"]:.2f}、WAPE {g["WAPE"]:.2%}；季节朴素MAE {b["MAE"]:.2f}，MAE改善 {1-g["MAE"]/b["MAE"]:.2%}。',
              f'2017全球名义80%/95%月区间覆盖率分别为{g["覆盖率80"]:.2%}/{g["覆盖率95"]:.2%}。样本只有12个月，不能认定覆盖率稳定达标。',
              '地区效果并非普遍优于基线，不能把全球指标替代地区检验。点预测为非负期望数量，可以为小数。十二地区逐月加总为全球，年度点预测等于十二个月之和，区间端点不可跨月或跨地区直接相加。', '',
              '## 空间演变', '',
              '| 年份 | 活跃格数 | 相对上年新增 | 相对上年消失 | 前十格事件占比 |',
              '| --- | ---: | ---: | ---: | ---: | ---: |']
    for _, r in tables['空间演变'].iterrows():
        new = '—' if pd.isna(r['相对上年新增格数']) else f'{r["相对上年新增格数"]:.0f}'
        lost = '—' if pd.isna(r['相对上年消失格数']) else f'{r["相对上年消失格数"]:.0f}'
        lines.append(f'| {int(r["年份"])} | {r["活跃格数"]:.0f} | {new} | {lost} | {r["前十格事件占比"]:.1%} |')
    lines += ['', '采用180×90等面积格网；新增仅相对前一年，不表示历史首次出现。第一年没有窗口内前期对照。', '',
              '## 原因、态势与建议', '']
    for _, r in tables['原因与建议'].iterrows():
        lines += [f'### {r["维度"]}', '', r['数据证据'], '', r['背景解释'], '', r['建议'], '', f'依据：{r["证据来源"]}。', '']
    lines += ['## 解释边界', '',
              '- 2012—2016滚动选模，2017为完整十二个月留出，不据测试结果换模型；2018使用同一方案重新拟合。',
              '- 区间使用选模期误差，有选模乐观偏差，不是独立校准的保覆盖区间；2017测试后才将其误差用于2018区间。',
              '- 月区间按步长季度合并误差估计RMS，年区间先逐年加总误差保留相关性；历史年份少且可能非平稳。',
              '- 按事件时间切分题目同一版数据，不是每年当时发布的历史快照，无法复原修订和发布延迟。',
              '- 2012年前后GTD采集变化影响较早回测，不能把记录数所有变化解释为真实风险变化。',
              '- 空间图只含有效坐标，坐标精度、漏报和网格分辨率影响热点边界。',
              '- 没有人口、旅客或设施暴露分母，计数不是个人遇袭概率。本次未使用2018实际结果验证。', '',
              '## 外部资料', '']
    for r in tables['参考资料'].to_dict('records'):
        lines.append(f'- {r["编号"]}：[{r["标题"]}]({r["链接"]})，{r["发布日期"]}。{r["用途"]}。')
    (output / '分析报告.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
